const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const Database = require('better-sqlite3');

const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'byteguard-integration-'));
process.env.DATABASE_PATH = path.join(directory, 'test.db');
process.env.JWT_SECRET = crypto.randomBytes(48).toString('hex');
process.env.NODE_ENV = 'test';
process.env.BCRYPT_ROUNDS = '10';
const { app } = require('../server');
const { db } = require('../db/database');
let server;
let base;
let checks = 0;
const password = crypto.randomBytes(18).toString('hex');

async function call(route, status = 200, { method = 'GET', body, cookie, headers = {} } = {}) {
  const response = await fetch(base + route, { method, headers: { ...(body === undefined ? {} : { 'Content-Type': 'application/json' }), ...(cookie ? { Cookie: cookie } : {}), ...headers }, body: body === undefined ? undefined : JSON.stringify(body) });
  const data = response.headers.get('content-type')?.includes('application/json') ? await response.json() : await response.text();
  assert.equal(response.status, status, `${method} ${route}: ${JSON.stringify(data)}`);
  checks += 1;
  return { data, cookie: response.headers.get('set-cookie')?.split(';')[0], response };
}

async function run() {
  try {
    server = await new Promise((resolve) => { const instance = app.listen(0, '127.0.0.1', () => resolve(instance)); });
    base = `http://127.0.0.1:${server.address().port}`;
    assert.equal((await call('/api/setup')).data.required, true);
    await call('/api/setup', 403, { method: 'POST', body: {}, headers: { 'X-Forwarded-For': '203.0.113.9' } });
    const untrustedHostStatus = await new Promise((resolve, reject) => {
      const request = require('node:http').request(base + '/api/setup', { method: 'POST', headers: { Host: 'untrusted.example', 'Content-Type': 'application/json' } }, (response) => {
        response.resume();
        response.on('end', () => resolve(response.statusCode));
      });
      request.on('error', reject);
      request.end('{}');
    });
    assert.equal(untrustedHostStatus, 403);
    checks += 1;
    const admin = await call('/api/setup', 201, { method: 'POST', body: { name: 'Administración de prueba', email: 'admin@example.test', password } });
    await call('/api/setup', 409, { method: 'POST', body: { name: 'Otra cuenta', email: 'second@example.test', password } });
    assert.equal((await call('/api/setup')).data.required, false);
    const writer = await call('/api/auth/register', 201, { method: 'POST', body: { name: 'Escritora de prueba', email: 'writer@example.test', password, role: 'admin' } });
    assert.equal(writer.data.user.role, 'writer');
    const outsider = await call('/api/auth/register', 201, { method: 'POST', body: { name: 'Otra escritora', email: 'outsider@example.test', password } });
    await call('/api/admin/users', 403, { cookie: writer.cookie });
    await call('/api/admin/comments', 401);
    await call('/api/posts', 401, { method: 'POST', body: {} });
    await call('/api/posts', 403, { method: 'POST', cookie: writer.cookie, body: {}, headers: { Origin: 'https://attacker.example' } });
    const content = '## Una guía útil\n\nUn artículo de seguridad para verificar formato y persistencia.\n\n- Primer paso\n- Segundo paso\n\n**Texto destacado**\n\n<script>alert(1)</script>\n\n[enlace](javascript:alert(1))';
    const payload = { title: 'Guía de prueba con acentos', excerpt: 'Un resumen útil para probar el flujo editorial completo.', category: 'Guía', content, contentFormat: 'markdown', status: 'draft' };
    const created = (await call('/api/posts', 201, { method: 'POST', body: payload, cookie: writer.cookie })).data.post;
    assert.ok(created.content.includes('<h2>Una guía útil</h2>'));
    assert.ok(created.content.includes('<strong>Texto destacado</strong>'));
    assert.ok(!created.content.includes('<script>'));
    assert.ok(!created.content.includes('href="javascript:'));
    assert.equal(created.contentSource, content);
    await call(`/api/posts/mine/${created.id}`, 403, { cookie: outsider.cookie });
    await call(`/api/posts/${created.id}`, 403, { method: 'PATCH', cookie: outsider.cookie, body: { title: 'Intrusión' } });
    await call(`/api/posts/${created.id}`, 403, { method: 'DELETE', cookie: outsider.cookie });
    await call(`/api/posts/${created.slug}`, 404);
    await call(`/api/posts/${created.id}`, 400, { method: 'PATCH', cookie: writer.cookie, body: { status: 'published' } });
    await call(`/api/admin/posts/${created.id}/publish`, 409, { method: 'PATCH', cookie: admin.cookie, body: {} });
    let post = (await call(`/api/posts/${created.id}`, 200, { method: 'PATCH', cookie: writer.cookie, body: { status: 'review', version: created.version } })).data.post;
    await call(`/api/posts/${created.id}`, 409, { method: 'PATCH', cookie: writer.cookie, body: { title: 'Versión antigua', version: created.version } });
    const reviewed = (await call(`/api/admin/posts/${created.id}`, 200, { cookie: admin.cookie })).data;
    assert.ok(reviewed.events.length >= 2);
    await call(`/api/admin/posts/${created.id}/return`, 400, { method: 'PATCH', cookie: admin.cookie, body: { note: '' } });
    post = (await call(`/api/admin/posts/${created.id}/return`, 200, { method: 'PATCH', cookie: admin.cookie, body: { note: 'Añade fuentes primarias y contexto.', version: post.version } })).data.post;
    assert.equal(post.status, 'draft');
    assert.match(post.reviewNote, /fuentes/);
    post = (await call(`/api/posts/${created.id}`, 200, { method: 'PATCH', cookie: writer.cookie, body: { status: 'review', version: post.version } })).data.post;
    await call(`/api/admin/posts/${created.id}/publish`, 409, { method: 'PATCH', cookie: admin.cookie, body: { version: post.version - 1 } });
    post = (await call(`/api/admin/posts/${created.id}/publish`, 200, { method: 'PATCH', cookie: admin.cookie, body: { version: post.version } })).data.post;
    assert.equal(post.status, 'published');
    const publicPost = (await call(`/api/posts/${created.slug}`)).data.post;
    assert.equal(publicPost.reviewNote, undefined);
    assert.equal(publicPost.contentSource, undefined);
    await call(`/api/posts/${created.id}`, 409, { method: 'PATCH', cookie: writer.cookie, body: { title: 'Edición no revisada' } });
    await call(`/api/posts/${created.id}`, 409, { method: 'DELETE', cookie: admin.cookie });
    await call(`/api/admin/posts/${created.id}/feature`, 200, { method: 'PATCH', cookie: admin.cookie, body: { featured: true } });
    assert.equal((await call('/api/posts')).data.posts[0].id, created.id);
    const search = (await call('/api/posts?q=GUIA%20DE%20PRUEBA&category=guia&limit=1')).data;
    assert.equal(search.pagination.total, 1);
    assert.equal(search.posts[0].id, created.id);
    assert.equal((await call('/api/posts?q=%25')).data.pagination.total, 0);
    const mine = (await call('/api/posts/mine?status=published&limit=1', 200, { cookie: writer.cookie })).data;
    assert.equal(mine.pagination.total, 1);
    assert.equal((await call('/api/posts/mine?status=draft', 200, { cookie: writer.cookie })).data.pagination.total, 0);
    await call(`/api/community/bookmarks/${created.id}`, 200, { method: 'PUT', cookie: writer.cookie, body: {} });
    await call(`/api/community/bookmarks/${created.id}`, 200, { method: 'PUT', cookie: writer.cookie, body: {} });
    assert.equal((await call('/api/community/bookmarks', 200, { cookie: writer.cookie })).data.posts.length, 1);
    await call(`/api/community/posts/${created.id}/comments`, 201, { method: 'POST', cookie: writer.cookie, body: { content: 'Un comentario constructivo para la comunidad.' } });
    assert.equal((await call(`/api/community/posts/${created.id}/comments`)).data.comments.length, 0);
    const comment = (await call('/api/admin/comments', 200, { cookie: admin.cookie })).data.comments[0];
    await call(`/api/admin/comments/${comment.id}`, 200, { method: 'PATCH', cookie: admin.cookie, body: { status: 'approved' } });
    assert.equal((await call(`/api/community/posts/${created.id}/comments`)).data.comments.length, 1);
    await call('/api/auth/profile', 200, { method: 'PATCH', cookie: writer.cookie, body: { name: 'Nombre actualizado', bio: 'Escribo sobre privacidad.' } });
    assert.equal((await call(`/api/posts/${created.slug}`)).data.post.author.name, 'Nombre actualizado');
    const rss = await call('/feed.xml');
    assert.match(rss.data, /Guía de prueba con acentos/);
    assert.ok(!rss.data.includes('Añade fuentes primarias'));
    await call(`/articulo/${created.slug}`);
    await call('/articulo/no-existe', 404);
    assert.match((await call('/sitemap.xml')).data, new RegExp(created.slug));
    await call('/data/byteguard.db', 404);
    await call('/.env', 404);
    await call('/api/auth/profile', 400, { method: 'PATCH', cookie: writer.cookie, body: { name: 'X', bio: '' } });
    const passwordChange = await call('/api/auth/password', 200, { method: 'PATCH', cookie: writer.cookie, body: { currentPassword: password, password: password + 'A' } });
    await call('/api/auth/me', 401, { cookie: writer.cookie });
    await call('/api/auth/me', 200, { cookie: passwordChange.cookie });
    await call(`/api/admin/users/${admin.data.user.id}`, 409, { method: 'PATCH', cookie: admin.cookie, body: { active: false } });
    await call(`/api/admin/users/${writer.data.user.id}`, 200, { method: 'PATCH', cookie: admin.cookie, body: { active: false } });
    await call('/api/auth/me', 401, { cookie: passwordChange.cookie });
    await call('/api/auth/login', 401, { method: 'POST', body: { email: 'writer@example.test', password: password + 'A' } });
    await call(`/api/admin/users/${writer.data.user.id}`, 200, { method: 'PATCH', cookie: admin.cookie, body: { active: true } });
    const login = await call('/api/auth/login', 200, { method: 'POST', body: { email: 'writer@example.test', password: password + 'A' } });
    await call('/api/auth/logout', 200, { method: 'POST', cookie: login.cookie, body: {} });
    await call('/api/auth/me', 401, { cookie: login.cookie });
    await call(`/api/admin/posts/${created.id}/return`, 200, { method: 'PATCH', cookie: admin.cookie, body: { note: 'Retirada para corregir una fuente.' } });
    await call(`/api/posts/${created.slug}`, 404);
    await call(`/api/community/posts/${created.id}/comments`, 404);
    assert.equal((await call('/api/community/bookmarks', 200, { cookie: admin.cookie })).data.posts.length, 0);
    const disk = new Database(process.env.DATABASE_PATH, { readonly: true });
    assert.equal(disk.prepare('SELECT source_content FROM posts WHERE id = ?').get(created.id).source_content, content);
    assert.equal(disk.prepare('PRAGMA user_version').get().user_version, 2);
    disk.close();
    await call(`/api/posts/${created.id}`, 200, { method: 'DELETE', cookie: admin.cookie });
    assert.equal(db.prepare('SELECT COUNT(*) AS n FROM bookmarks WHERE post_id = ?').get(created.id).n, 0);
    assert.equal(db.prepare('SELECT COUNT(*) AS n FROM comments WHERE post_id = ?').get(created.id).n, 0);
    const insert = db.prepare("INSERT INTO posts (author_id, title, slug, excerpt, content, category, status) VALUES (?, ?, ?, ?, ?, 'Seguridad', 'draft')");
    for (let index = 0; index < 13; index += 1) insert.run(writer.data.user.id, `Borrador ${index}`, `pagination-${index}`, 'Resumen para verificar paginación.', '<p>Contenido de ejemplo para comprobar la paginación editorial.</p>');
    const fresh = await call('/api/auth/login', 200, { method: 'POST', body: { email: 'writer@example.test', password: password + 'A' } });
    const page1 = (await call('/api/posts/mine?limit=10&offset=0', 200, { cookie: fresh.cookie })).data;
    const page2 = (await call('/api/posts/mine?limit=10&offset=10', 200, { cookie: fresh.cookie })).data;
    assert.equal(page1.pagination.total, 13);
    assert.equal(page1.posts.length, 10);
    assert.equal(page2.posts.length, 3);
    assert.ok(page1.posts.every((post) => !page2.posts.some((other) => other.id === post.id)));
    console.info(`${checks} comprobaciones HTTP superadas: configuración, RBAC, flujo editorial, búsqueda, moderación, guardados, persistencia y revocación de sesiones.`);
  } finally {
    if (server) await new Promise((resolve) => server.close(resolve));
    db.close();
    fs.rmSync(directory, { recursive: true, force: true });
  }
}
run().catch((error) => { console.error(error); process.exitCode = 1; });
